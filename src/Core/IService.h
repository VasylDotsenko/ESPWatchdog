#pragma once

//=============================================================================
// IService
//=============================================================================
//
// Базовий інтерфейс усіх сервісів системи.
//
// Життєвий цикл:
//
// 1. begin()  - одноразова ініціалізація сервісу.
// 2. loop()   - періодичне обслуговування сервісу.
//
// Усі сервіси проєкту повинні реалізовувати цей інтерфейс.
//=============================================================================

class IService
{
public:

    virtual ~IService() = default;

    //-------------------------------------------------------------------------
    // Ініціалізація сервісу.
    // Повертає true при успішній ініціалізації.
    //-------------------------------------------------------------------------
    virtual bool begin() = 0;

    //-------------------------------------------------------------------------
    // Основний цикл сервісу.
    // Викликається Application::loop().
    //-------------------------------------------------------------------------
    virtual void loop() = 0;
};