#pragma once

#include <Arduino.h>

//=============================================================================
// Network Protocol
//=============================================================================

enum class NetworkProtocol : uint8_t
{
    ICMP = 0,
    TCP,
    HTTP,
    MQTT
};

//=============================================================================
// Network Session State
//=============================================================================

enum class NetworkSessionState : uint8_t
{
    Idle = 0,

    Resolving,

    Connecting,

    Running,

    Finished,

    Error
};

//=============================================================================
// Network Address
//=============================================================================

struct NetworkAddress
{
    const char* host = nullptr;

    uint16_t port = 0;
};

//=============================================================================
// Network Timeout
//=============================================================================

struct NetworkTimeout
{
    uint32_t connect = 1000;

    uint32_t response = 1000;
};