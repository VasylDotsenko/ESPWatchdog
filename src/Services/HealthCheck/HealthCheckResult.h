#pragma once

#include <Arduino.h>

//=============================================================================
// Health Check Status
//=============================================================================

enum class HealthCheckStatus : uint8_t
{
    Success = 0,

    Timeout,

    HostUnreachable,

    NetworkUnavailable,

    DnsFailed,

    Cancelled,

    Error
};

//=============================================================================
// Health Check Result
//=============================================================================
//
// Результат однієї перевірки доступності вузла.
// Не містить статистики — лише інформацію про останню виконану перевірку.
//
//=============================================================================

struct HealthCheckResult
{
    //---------------------------------------------------------------------
    // Загальний результат перевірки
    //---------------------------------------------------------------------

    bool success = false;

    //---------------------------------------------------------------------
    // Детальний статус
    //---------------------------------------------------------------------

    HealthCheckStatus status = HealthCheckStatus::Error;

    //---------------------------------------------------------------------
    // Час відповіді, мс
    //---------------------------------------------------------------------

    uint32_t responseTime = 0;
};