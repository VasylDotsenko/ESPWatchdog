#pragma once

#include "NetworkResult.h"

//=============================================================================
// INetworkSession
//=============================================================================
//
// Base interface for asynchronous network sessions.
//
// Implementations:
//
//   • ICMP
//   • TCP
//   • HTTP
//   • MQTT
//
//=============================================================================

class INetworkSession
{
public:

    virtual ~INetworkSession() = default;

    //---------------------------------------------------------------------
    // Initialization
    //---------------------------------------------------------------------

    virtual bool begin() = 0;

    //---------------------------------------------------------------------
    // Start session
    //---------------------------------------------------------------------

    virtual bool start(
        const char* host,
        uint16_t port = 0,
        uint32_t timeout = 1000) = 0;

    //---------------------------------------------------------------------
    // Processing
    //---------------------------------------------------------------------

    virtual void loop() = 0;

    //---------------------------------------------------------------------
    // State
    //---------------------------------------------------------------------

    virtual bool running() const = 0;

    virtual bool finished() const = 0;

    //---------------------------------------------------------------------
    // Result
    //---------------------------------------------------------------------

    virtual const NetworkResult& result() const = 0;

    //---------------------------------------------------------------------
    // Information
    //---------------------------------------------------------------------

    virtual const char* name() const = 0;
};