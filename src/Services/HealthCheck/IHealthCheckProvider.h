#pragma once

#include <Arduino.h>

#include "HealthCheckResult.h"

//=============================================================================
// IHealthCheckProvider
//=============================================================================
//
// Абстрактний інтерфейс перевірки доступності вузла.
//
// Реалізації:
//
//  • ICMP Ping
//  • TCP Connect
//  • HTTP GET
//  • HTTPS GET
//  • MQTT Connect
//  • Mock Provider (Unit Tests)
//
// Провайдер виконує одну перевірку доступності вузла та повертає
// результат через HealthCheckResult.
//
//=============================================================================

class IHealthCheckProvider
{
public:

    virtual ~IHealthCheckProvider() = default;

    //---------------------------------------------------------------------
    // Initialization
    //---------------------------------------------------------------------

    virtual bool begin() = 0;

    //---------------------------------------------------------------------
    // Start health check
    //
    // host      - DNS name або IP
    // timeoutMs - максимальний час виконання перевірки
    //---------------------------------------------------------------------

    virtual bool start(
        const char* host,
        uint32_t timeoutMs) = 0;

    //---------------------------------------------------------------------
    // Background processing
    //---------------------------------------------------------------------

    virtual void loop() = 0;

    //---------------------------------------------------------------------
    // Is check currently running
    //---------------------------------------------------------------------

    virtual bool running() const = 0;

    //---------------------------------------------------------------------
    // Has current check finished
    //---------------------------------------------------------------------

    virtual bool finished() const = 0;

    //---------------------------------------------------------------------
    // Cancel current operation
    //---------------------------------------------------------------------

    virtual void cancel() = 0;

    //---------------------------------------------------------------------
    // Last result
    //---------------------------------------------------------------------

    virtual const HealthCheckResult& result() const = 0;
};