#pragma once

#include <Arduino.h>

#include "Core/IService.h"
#include "Core/Timer.h"

#include "HealthCheckInfo.h"
#include "Models/HealthStatusData.h"
#include "IHealthCheckProvider.h"

//=============================================================================
// HealthCheckService
//=============================================================================
//
// Координує перевірку доступності вузла.
//
// Відповідає за:
//
//  • запуск перевірок;
//  • накопичення статистики;
//  • поточний стан вузла.
//
// Не залежить від конкретної реалізації перевірки
// (ICMP, TCP, HTTP, MQTT тощо).
//
//=============================================================================

class HealthCheckService : public IService
{
public:

    HealthCheckService() = default;

    //---------------------------------------------------------------------
    // Dependency Injection
    //---------------------------------------------------------------------

    void setProvider(IHealthCheckProvider& provider);

    //---------------------------------------------------------------------
    // IService
    //---------------------------------------------------------------------

    bool begin() override;

    void loop() override;

    //---------------------------------------------------------------------
    // Current state
    //---------------------------------------------------------------------

    [[nodiscard]]
    bool online() const;

    [[nodiscard]]
    bool running() const;

    //---------------------------------------------------------------------
    // Information
    //---------------------------------------------------------------------

    [[nodiscard]]
    const HealthCheckInfo& info() const;

    [[nodiscard]]
    HealthStatusData status() const;

    //---------------------------------------------------------------------
    // Maintenance
    //---------------------------------------------------------------------

    void reset();

private:

    //---------------------------------------------------------------------
    // Internal state machine
    //---------------------------------------------------------------------

    enum class State : uint8_t
    {
        Idle,
        Waiting
    };

private:

    //---------------------------------------------------------------------
    // Workflow
    //---------------------------------------------------------------------

    void startCheck();

    void processResult();

private:

    //---------------------------------------------------------------------
    // Dependencies
    //---------------------------------------------------------------------

    IHealthCheckProvider* m_provider = nullptr;

    //---------------------------------------------------------------------
    // Timer
    //---------------------------------------------------------------------

    Timer m_timer;

    //---------------------------------------------------------------------
    // State machine
    //---------------------------------------------------------------------

    State m_state = State::Idle;

    //---------------------------------------------------------------------
    // Runtime information
    //---------------------------------------------------------------------

    HealthCheckInfo m_info;
};

//=============================================================================

extern HealthCheckService HealthCheck;
